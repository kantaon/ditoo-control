def weather_icon(code, is_day=True):
    """WMO weather code -> (art, palette)."""
    sun = {"#": (255, 200, 0)}
    moon = {"#": (220, 220, 160)}
    cloud = {"#": (170, 180, 195)}
    if code in (0, 1):
        return (SUN, sun) if is_day else (MOON, moon)
    if code == 2:
        if not is_day:
            return CLOUD, cloud
        return SUN_CLOUD, {"#": (200, 200, 210)}
    if code == 3:
        return CLOUD, cloud
    if code in (45, 48):
        return FOG, {"#": (140, 140, 150)}
    if code in (71, 73, 75, 77, 85, 86):
        return SNOW, {"#": (170, 180, 195), "*": WHITE}
    if code in (95, 96, 99):
        return STORM, {"#": (110, 115, 130), "/": (255, 230, 0)}
    return RAIN, {"#": (130, 140, 160)}


def temp_color(t, warn, crit):
    if t is None:
        return (90, 90, 90)
    if t >= crit:
        return (255, 30, 20)
    if t >= warn:
        return (255, 140, 0)
    if t >= warn - 15:
        return (230, 220, 0)
    return (0, 220, 90)


def usage_color(frac):
    return lerp((0, 160, 255), (255, 40, 40), max(0.0, min(1.0, frac)))
