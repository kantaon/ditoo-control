_DIACRITICS = str.maketrans("ÁČĎÉĚÍŇÓŘŠŤÚŮÝŽ", "ACDEEINORSTUUYZ")


NARROW = set("°:.!'")  # punctuation is drawn only as wide as its ink


def _glyph_cols(g, ch, w):
    """(first column, width) actually used by a glyph; monospace except punctuation."""
    if ch not in NARROW:
        return 0, w
    cols = [x for x in range(w) if any(row[x] == "#" for row in g)]
    return (cols[0], cols[-1] - cols[0] + 1) if cols else (0, 1)


def text_width(text, font=3):
    glyphs, w, _ = FONTS[font]
    total = 0
    for ch in str(text).upper().translate(_DIACRITICS):
        g = glyphs.get(ch) or glyphs.get(" ")
        total += _glyph_cols(g, ch, w)[1] + 1
    return max(0, total - 1)


def scale(color, f):
    return tuple(max(0, min(255, int(c * f))) for c in color)


def lerp(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


class Canvas:
    def __init__(self, w=SIZE, h=SIZE, bg=BLACK):
        self.w, self.h = w, h
        self.px = [bg] * (w * h)

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y * self.w + x] = c

    def get(self, x, y):
        return self.px[y * self.w + x]

    def fill(self, c):
        self.px = [c] * (self.w * self.h)
        return self

    def rect(self, x, y, w, h, c):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.set(xx, yy, c)

    def text(self, x, y, text, color, font=3):
        glyphs, w, _ = FONTS[font]
        for ch in str(text).upper().translate(_DIACRITICS):
            g = glyphs.get(ch) or glyphs.get(" ")
            first, cw = _glyph_cols(g, ch, w)
            for gy, row in enumerate(g):
                for gx, bit in enumerate(row):
                    if bit == "#":
                        self.set(x + gx - first, y + gy, color)
            x += cw + 1
        return x

    def text_center(self, y, text, color, font=3):
        self.text((self.w - text_width(text, font)) // 2, y, text, color, font)

    def bar(self, x, y, w, frac, color, bg=(25, 25, 25)):
        n = round(max(0.0, min(1.0, frac)) * w)
        for i in range(w):
            self.set(x + i, y, color if i < n else bg)

    def icon(self, x, y, art, palette):
        for yy, row in enumerate(art):
            for xx, ch in enumerate(row):
                if ch in palette:
                    self.set(x + xx, y + yy, palette[ch])

    def crop(self, x0, w=SIZE):
        """16-wide window of a wider canvas (for scrolling text)."""
        out = Canvas()
        for y in range(min(self.h, SIZE)):
            for x in range(w):
                sx = x0 + x
                if 0 <= sx < self.w:
                    out.set(x, y, self.get(sx, y))
        return out

    def pixels(self):
        return list(self.px)


